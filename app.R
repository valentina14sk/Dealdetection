server <- function(input, output, session) {
  outputs <- reactiveVal(NULL)
  status <- reactiveVal("Enter the path to your DealDetective_Output folder, then click Load analysis outputs.")
  
  observeEvent(input$load_outputs, {
    folder <- path.expand(trimws(input$folder))
    if (!dir.exists(folder)) {
      outputs(NULL)
      status(paste("Folder not found:", folder, "— check the path and try again."))
      return()
    }
    expected <- c("01_missing_values.csv", "03_discount_summary.csv", "18_final_project_summary.csv")
    found <- expected[file.exists(file.path(folder, expected))]
    if (!length(found)) {
      outputs(NULL)
      status("The folder exists, but the expected DealDetective CSV summaries were not found. Select the DealDetective_Output folder created by your original R script.")
      return()
    }
    data <- list(
      folder=folder,
      missing=read_if_exists(folder,"01_missing_values.csv"),
      flags=read_if_exists(folder,"09_flag_summary.csv"),
      consistency=read_if_exists(folder,"10_discount_formula_validation.csv"),
      sample=read_if_exists(folder,"18_final_project_summary.csv"),
      products=read_if_exists(folder,"16_product_warning_summary.csv"),
      weekly=read_if_exists(folder,"15_weekly_correlations.csv"),
      bands=read_if_exists(folder,"05_discount_band_summary.csv"),
      flag_summary=read_if_exists(folder,"09_flag_summary.csv"),
      candidates=read_if_exists(folder,"12_potential_warning_cases.csv")
    )
    outputs(data)
    status(paste("Loaded output folder:", folder))
  }, ignoreInit=TRUE)
  
  output$status_ui <- renderUI({
    x <- outputs()
    if (is.null(x)) div(class="status-box", h4("Connect your existing analysis"),
                        p(status()),
                        p("No example results are shown. Once loaded, the dashboard displays files created by your original R script.")
    ) else div(class="status-box", strong("Output folder loaded · "), status())
  })
  
  output$metrics_ui <- renderUI({
    x <- outputs(); if (is.null(x)) return(NULL)
    sm <- x$sample
    getv <- function(label) {
      if (is.null(sm) || !nrow(sm)) return("—")
      # Display a useful value from the actual project summary without assuming column names.
      if (ncol(sm) >= 2) return(as.character(sm[[2]][1]))
      as.character(sm[[1]][1])
    }
    cand <- if (is.null(x$candidates)) "—" else format(nrow(x$candidates),big.mark=",")
    prod <- if (is.null(x$products)) "—" else format(nrow(x$products),big.mark=",")
    metric <- function(label,value,note) div(class="col-sm-3 col-xs-6",
                                             div(class="metric-card",div(class="metric-label",label),div(class="metric-value",value),div(class="metric-note",note)))
    fluidRow(
      metric("Project summary",getv("summary"),"From original R run"),
      metric("Summary records",if(is.null(sm)) "—" else format(nrow(sm),big.mark=","),"Rows in final summary file"),
      metric("Product warning records",prod,"From product warning summary"),
      metric("Review candidates",cand,"Potential warning cases; not proof of deception")
    )
  })
  
  image_ui <- function(id, filename, label) {
    renderUI({
      x <- outputs(); if (is.null(x)) return(p(class="small-note","Load output folder to view chart."))
      path <- file.path(x$folder, filename)
      if (!file.exists(path)) return(p(class="small-note",paste("Chart not found:", filename)))
      tags$img(src=paste0("chart_",id), class="chart-image", alt=label)
    })
  }
  # Serve existing local PNGs through Shiny's resource path, without copying them.
  output$img07 <- image_ui("07","11_selected_product_price_history.png","Historical price trend")
  output$img08 <- image_ui("08","02_discount_vs_30day_average.png","Discount vs 30-day average")
  output$img09 <- image_ui("09","01_discount_distribution.png","Discount distribution")
  output$img11 <- image_ui("11","03_discount_bands_vs_30day_average.png","Discount-band comparison")
  output$img13 <- image_ui("13","08_dataset_flag_comparison.png","Dataset-provided flags")
  output$img14 <- image_ui("14","06_platform_discount_comparison.png","Weekly discount by platform")
  output$img15 <- image_ui("15","04_discount_vs_52week_minimum.png","Weekly price difference by platform")
  
  # Register the currently selected output folder's PNG directory as a Shiny resource.
  observe({
    x <- outputs()
    if (!is.null(x) && dir.exists(x$folder)) {
      addResourcePath("dealdetective_charts", x$folder)
    }
  })
  # Rewrite chart sources to the registered resource path.
  output$img07 <- renderUI({ x<-outputs(); if(is.null(x)) return(p("Load output folder to view chart.")); f<-"11_selected_product_price_history.png"; if(!file.exists(file.path(x$folder,f))) return(p(class="small-note",paste("Chart not found:",f))); tags$img(src=paste0("dealdetective_charts/",f),class="chart-image",alt="Historical price trend") })
  output$img08 <- renderUI({ x<-outputs(); if(is.null(x)) return(p("Load output folder to view chart.")); f<-"02_discount_vs_30day_average.png"; if(!file.exists(file.path(x$folder,f))) return(p(class="small-note",paste("Chart not found:",f))); tags$img(src=paste0("dealdetective_charts/",f),class="chart-image",alt="Discount vs 30-day average") })
  output$img09 <- renderUI({ x<-outputs(); if(is.null(x)) return(p("Load output folder to view chart.")); f<-"01_discount_distribution.png"; if(!file.exists(file.path(x$folder,f))) return(p(class="small-note",paste("Chart not found:",f))); tags$img(src=paste0("dealdetective_charts/",f),class="chart-image",alt="Discount distribution") })
  output$img11 <- renderUI({ x<-outputs(); if(is.null(x)) return(p("Load output folder to view chart.")); f<-"03_discount_bands_vs_30day_average.png"; if(!file.exists(file.path(x$folder,f))) return(p(class="small-note",paste("Chart not found:",f))); tags$img(src=paste0("dealdetective_charts/",f),class="chart-image",alt="Discount-band comparison") })
  output$img13 <- renderUI({ x<-outputs(); if(is.null(x)) return(p("Load output folder to view chart.")); f<-"08_dataset_flag_comparison.png"; if(!file.exists(file.path(x$folder,f))) return(p(class="small-note",paste("Chart not found:",f))); tags$img(src=paste0("dealdetective_charts/",f),class="chart-image",alt="Dataset-provided flags") })
  output$img14 <- renderUI({ x<-outputs(); if(is.null(x)) return(p("Load output folder to view chart.")); f<-"06_platform_discount_comparison.png"; if(!file.exists(file.path(x$folder,f))) return(p(class="small-note",paste("Chart not found:",f))); tags$img(src=paste0("dealdetective_charts/",f),class="chart-image",alt="Weekly discount by platform") })
  output$img15 <- renderUI({ x<-outputs(); if(is.null(x)) return(p("Load output folder to view chart.")); f<-"04_discount_vs_52week_minimum.png"; if(!file.exists(file.path(x$folder,f))) return(p(class="small-note",paste("Chart not found:",f))); tags$img(src=paste0("dealdetective_charts/",f),class="chart-image",alt="Weekly price difference by platform") })
  
  output$missing_table <- renderDT({
    x<-outputs(); req(x)
    validate(need(!is.null(x$missing),"01_missing_values.csv was not found."))
    datatable(as.data.frame(x$missing),rownames=FALSE,filter="top",options=list(pageLength=15,scrollX=TRUE))
  })
  output$consistency_table <- renderDT({
    x<-outputs(); req(x)
    validate(need(!is.null(x$consistency),"10_discount_formula_validation.csv was not found."))
    datatable(as.data.frame(x$consistency),rownames=FALSE,options=list(dom="t",scrollX=TRUE))
  })
  output$flags_table <- renderDT({
    x<-outputs(); req(x)
    d <- x$flags
    validate(need(!is.null(d),"09_flag_summary.csv was not found."))
    datatable(as.data.frame(d),rownames=FALSE,options=list(pageLength=10,scrollX=TRUE))
  })
  output$sample_table <- renderDT({
    x<-outputs(); req(x)
    validate(need(!is.null(x$sample),"18_final_project_summary.csv was not found."))
    datatable(as.data.frame(x$sample),rownames=FALSE,options=list(dom="t",scrollX=TRUE))
  })
  output$weekly_table <- renderDT({
    x<-outputs(); req(x)
    validate(need(!is.null(x$weekly),"15_weekly_correlations.csv was not found."))
    datatable(as.data.frame(x$weekly),rownames=FALSE,filter="top",options=list(pageLength=15,scrollX=TRUE))
  })
  output$weekly_discount_plot <- renderPlot({
    plot.new(); text(.5,.5,"Weekly chart requires weekly history data, which this output set does not include.")
  })
  output$weekly_price_plot <- renderPlot({
    plot.new(); text(.5,.5,"Weekly chart requires weekly history data, which this output set does not include.")
  })
  output$candidates_table <- renderDT({
    x<-outputs(); req(x)
    validate(need(!is.null(x$candidates),"12_potential_warning_cases.csv was not found."))
    datatable(as.data.frame(x$candidates),rownames=FALSE,filter="top",options=list(pageLength=15,scrollX=TRUE))
  })
  output$products_table <- renderDT({
    x<-outputs(); req(x)
    validate(need(!is.null(x$products),"16_product_warning_summary.csv was not found."))
    datatable(as.data.frame(x$products),rownames=FALSE,filter="top",options=list(pageLength=15,scrollX=TRUE))
  })
  output$download_candidates <- downloadHandler(
    filename=function() paste0("dealdetective_review_candidates_",Sys.Date(),".csv"),
    content=function(file) { x<-outputs(); req(x$candidates); fwrite(x$candidates,file) }
  )
  output$download_products <- downloadHandler(
    filename=function() paste0("dealdetective_product_summary_",Sys.Date(),".csv"),
    content=function(file) { x<-outputs(); req(x$products); fwrite(x$products,file) }
  )
}

shinyApp(ui, server)
