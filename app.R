fmt_num <- function(x) {
  if (length(x) == 0 || is.na(x) || !is.finite(suppressWarnings(as.numeric(x)))) return("—")
  format(round(as.numeric(x)), big.mark = ",", scientific = FALSE, trim = TRUE)
}
read_if_exists <- function(folder, filename) {
  path <- file.path(folder, filename)
  if (!file.exists(path)) return(NULL)
  tryCatch(fread(path), error = function(e) NULL)
}
png_if_exists <- function(folder, filename) file.path(folder, filename)

